#!/usr/bin/env python3
"""Generate Swift keycode tables from QMK's data/constants/keycodes/*.hjson.

Usage (needs a QMK checkout, a sparse one is enough):
    git clone --depth 1 --filter=blob:none --sparse https://github.com/qmk/qmk_firmware.git /tmp/qmk
    git -C /tmp/qmk sparse-checkout set --no-cone '/data/constants/keycodes/'
    uv run --with hjson Tools/gen-keycodes.py /tmp/qmk

The merge rules mirror qmk_firmware/lib/python/qmk/keycodes.py and json_schema.py:
every version up to the requested one is loaded, files are grouped by fragment
("_" for the base file, "basic", "lighting", ...), each group is merged in version
order ("!delete!" removes a key, "!reset!" replaces a dict or list), then groups are
deep-merged into one spec.
"""
import sys
from collections import OrderedDict
from collections.abc import Mapping
from pathlib import Path

import hjson

# QMK keycode spec versions we ship tables for.
# 0.0.7 backs VIA protocol 12 (no keycodes version reported); 0.0.8 and 0.0.9 back protocol 13.
VERSIONS = ["0.0.7", "0.0.8", "0.0.9"]

OUT_DIR = Path(__file__).resolve().parent.parent / "Packages/MicrokitCore/Sources/MicrokitCore/Keycodes/Generated"


def merge_ordered_dicts(dicts):
    result = OrderedDict()

    def add_entry(target, k, v):
        if k in target and isinstance(v, (OrderedDict, dict)):
            if "!reset!" in v:
                target[k] = v
            else:
                target[k] = merge_ordered_dicts([target[k], v])
            if "!reset!" in target[k]:
                del target[k]["!reset!"]
        elif k in target and isinstance(v, list):
            target[k] = v[1:] if v and v[0] == "!reset!" else target[k] + v
        elif v == "!delete!" and isinstance(target, (OrderedDict, dict)):
            target.pop(k, None)
        else:
            target[k] = v

    for d in dicts:
        for k, v in d.items():
            add_entry(result, k, v)
    return result


def deep_update(orig, new):
    for k, v in new.items():
        if isinstance(v, Mapping):
            orig[k] = deep_update(orig.get(k, {}), v)
        else:
            orig[k] = v
    return orig


def all_versions(path):
    found = sorted({f.stem.split("_")[1] for f in path.glob("keycodes_[0-9].[0-9].[0-9]*.hjson")})
    return found


def load_spec(path, version):
    versions = [v for v in all_versions(path) if v <= version]
    groups = {"_": []}
    for v in versions:
        groups["_"].append(path / f"keycodes_{v}.hjson")
        for f in sorted(path.glob(f"keycodes_{v}_*.hjson")):
            groups.setdefault(f.stem.replace(f"keycodes_{v}_", ""), []).append(f)
    spec = {}
    for files in groups.values():
        specs = [hjson.load(open(f), object_pairs_hook=OrderedDict) for f in files if f.exists()]
        deep_update(spec, merge_ordered_dicts(specs))
    return spec


def swift_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def emit(version, spec):
    ident = version.replace(".", "_")
    lines = [
        "// GENERATED by Tools/gen-keycodes.py from QMK data/constants/keycodes. Do not edit.",
        f"// QMK keycode spec {version}.",
        "",
        "extension QMKKeycodeSpec {",
        f"    static let v{ident} = QMKKeycodeSpec(",
        f"        version: {swift_string(version)},",
        "        ranges: [",
    ]
    for key, val in sorted(spec.get("ranges", {}).items(), key=lambda kv: int(kv[0].split("/")[0], 16)):
        start, mask = (int(x, 16) for x in key.split("/"))
        lines.append(f"            .init(start: 0x{start:04X}, last: 0x{start + mask:04X}, define: {swift_string(val['define'])}),")
    lines.append("        ],")
    lines.append("        keycodes: [")
    for code, val in sorted(spec.get("keycodes", {}).items(), key=lambda kv: int(kv[0], 16)):
        aliases = ", ".join(swift_string(a) for a in val.get("aliases", []))
        label = val.get("label")
        label_s = swift_string(label) if label is not None else "nil"
        lines.append(
            f"            .init(code: 0x{int(code, 16):04X}, key: {swift_string(val['key'])}, label: {label_s}, "
            f"group: {swift_string(val.get('group', ''))}, aliases: [{aliases}]),"
        )
    lines.append("        ]")
    lines.append("    )")
    lines.append("}")
    lines.append("")
    out = OUT_DIR / f"QMKKeycodes_{ident}.swift"
    out.write_text("\n".join(lines))
    print(f"{out.relative_to(OUT_DIR.parent.parent.parent.parent.parent.parent)}: "
          f"{len(spec.get('keycodes', {}))} keycodes, {len(spec.get('ranges', {}))} ranges")


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    path = Path(sys.argv[1]) / "data/constants/keycodes"
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for version in VERSIONS:
        emit(version, load_spec(path, version))


if __name__ == "__main__":
    main()
